    /** Merged station list — the ported upstream set plus [GANGNEUNG_LINE_ADDITIONS]. */
    val STATIONS: List<Station> = ALL + GANGNEUNG_LINE_ADDITIONS

    private val KOREAN_COLLATOR: Collator = Collator.getInstance(Locale.KOREAN)

    /** All station names, de-duplicated and 가나다-sorted so the picker list and 자음 jump tabs stay in order regardless of insertion order. */
    val NAMES: List<String> = STATIONS.map { it.name }.distinct().sortedWith(KOREAN_COLLATOR)

    private val CHOSEONG = charArrayOf(
        'ㄱ', 'ㄲ', 'ㄴ', 'ㄷ', 'ㄸ', 'ㄹ', 'ㅁ', 'ㅂ', 'ㅃ', 'ㅅ',
        'ㅆ', 'ㅇ', 'ㅈ', 'ㅉ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ'
    )

    /** The 자음 tabs to offer for jump-to-letter, limited to consonants that actually start a station name. */
    val AVAILABLE_INITIALS: List<Char> by lazy {
        CHOSEONG.filter { initial -> NAMES.any { choseongOf(it.firstOrNull() ?: ' ') == initial } }
    }

    private fun choseongOf(c: Char): Char? {
        if (c.code < 0xAC00 || c.code > 0xD7A3) return null
        val index = (c.code - 0xAC00) / (21 * 28)
        return CHOSEONG[index]
    }

    private fun choseongString(s: String): String = s.map { choseongOf(it) ?: it }.joinToString("")

    /** True if [name] matches [query] — as plain substring, or as 초성(initial-consonant) search when [query] is all-초성. */
    fun matches(name: String, query: String): Boolean {
        if (query.isBlank()) return true
        val isChoseongQuery = query.all { it in CHOSEONG }
        return if (isChoseongQuery) choseongString(name).contains(query) else name.contains(query)
    }

    /** Index of the first station whose name starts with [initial], or -1. */
    fun firstIndexOf(initial: Char): Int = NAMES.indexOfFirst { choseongOf(it.firstOrNull() ?: ' ') == initial }
}
